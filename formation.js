// تعبئة البيانات

function showClass(index) {

    const cls = classes[index];

    document.getElementById("grade").textContent = cls.grade;
    document.getElementById("teacher").textContent = cls.teacher;

    document.getElementById("boys").textContent = cls.boys;
    document.getElementById("girls").textContent = cls.girls;
    document.getElementById("total").textContent = cls.total;
    document.getElementById("room").textContent = cls.room;
    document.getElementById("floor").textContent = cls.floor;

    const tbody = document.getElementById("subjects");

    tbody.innerHTML = "";

    cls.subjects.forEach(item => {

        tbody.innerHTML += `
            <tr>
                <td>${item.subject}</td>
                <td>${item.teacher}</td>
            </tr>
        `;

    });

}

// أول تحميل

showClass(0);

// أزرار الصفوف

const buttons = document.querySelectorAll(".class-btn");

buttons.forEach((btn, index) => {

    btn.addEventListener("click", () => {

        buttons.forEach(b => b.classList.remove("active"));

        btn.classList.add("active");

        showClass(index);

    });

});